export function getCaseClientTitle(item: Pick<Case, "slug" | "title">): string {
  return CASE_CLIENT_TITLES[item.slug] ?? item.title;
}

function inferCapabilities(source: CaseSource): CapabilityId[] {
  const capabilities = new Set<CapabilityId>(CAPABILITIES_BY_CATEGORY[source.category]);
  const haystack = [
    source.title,
    source.type,
    source.excerpt,
    source.solution,
    ...source.technologies,
    ...source.automation,
  ]
    .join(" ")
    .toLowerCase();

  if (haystack.includes("rag") || haystack.includes("база знаний") || haystack.includes("источник")) {
    capabilities.add("rag-knowledge-systems");
  }
  if (haystack.includes("n8n") || haystack.includes("api") || haystack.includes("webhook")) {
    capabilities.add("automation-pipelines");
  }
  if (haystack.includes("crm") || haystack.includes("админ")) {
    capabilities.add("crm-automation");
  }
  if (haystack.includes("e-commerce") || haystack.includes("каталог") || haystack.includes("checkout")) {
    capabilities.add("ecommerce-ai");
  }
  if (haystack.includes("seo") || haystack.includes("geo") || haystack.includes("контент")) {
    capabilities.add("content-factories");
  }
  if (haystack.includes("geo")) {
    capabilities.add("geo-ai-search");
  }

  return [...capabilities];
}

function inferIntegrations(source: CaseSource): string[] {
  const integrationNames = ["n8n", "Telegram", "WordPress", "1C", "GSC", "API", "DOCX", "WhatsApp", "NASA"];
  return integrationNames.filter((name) => {
    const normalized = name.toLowerCase();
    return [source.title, source.solution, ...source.technologies, ...source.automation]
      .join(" ")
      .toLowerCase()
      .includes(normalized);
  });
}

function normalizeCase(source: CaseSource): Case {
  return {
    ...source,
    clientTitle: source.clientTitle ?? CASE_CLIENT_TITLES[source.slug] ?? source.title,
    shortTitle: source.shortTitle ?? SHORT_TITLES[source.slug] ?? source.title,
    summary: source.summary ?? source.excerpt,
    businessProblem: source.businessProblem ?? source.task,
    automationHighlights: source.automationHighlights ?? source.automation,
    architectureHighlights: source.architectureHighlights ?? source.howItWorks,
    stack: source.stack ?? source.technologies,
    integrations: source.integrations ?? inferIntegrations(source),
    scale:
      source.scale ??
      "Масштаб описан через публично раскрытые границы проекта: статус, период, роли, интеграции и набор автоматизированных операций без неподтверждённых метрик.",
    result: source.result ?? source.businessValue,
    tags: source.tags ?? source.technologies,
    relatedCapabilities: source.relatedCapabilities ?? inferCapabilities(source),
  };
}

